function buildJsonLd(q, url) {
  const s = q.schema || {};
  const quotation = {
    '@type': 'Quotation',
    '@id': `${url}#quotation`,
    text: s.quotationText || q.fullQuote || q.displayQuote,
  };
  if (s.alternateName) quotation.alternateName = s.alternateName;
  // NOTE: schema.inLanguage is NOT emitted yet, though the CLAUDE.md RULE requires it and records
  // already carry it. Wiring it up naively mis-tags translated quotations: records whose `text` is a
  // published English translation (e.g. Meditations via Staniforth) set inLanguage to the ORIGINAL
  // composition language ("grc"), so emitting it as-is would assert an English sentence is Ancient
  // Greek. Needs a site-wide pass that settles the semantics (language of `text`, not of the source)
  // and audits existing values before it can be turned on.
  // Quotation.creator must name the TRUE author. On a DISPUTED page, generate sometimes left the
  // magnet (the wrongly-credited name) in schema.creator — a machine-readable contradiction of the
  // page's own verdict. So on disputed pages, only assert a creator when it genuinely matches the
  // true author (answer.authorName) and that author is a real named person; otherwise omit it. The
  // disputed claimant is still carried by the ClaimReview below, so nothing is lost.
  const heroName = plain((q.answer && q.answer.authorName) || '');
  const heroUnknown = !heroName || /\b(unknown|anonymous|unattributed|uncertain)\b/i.test(heroName);
  const magnetName = plain(q.creditedTo || '').toLowerCase();
  // A WORDING-DRIFT page: the credited name IS the true author and the dispute is the WORDING, not
  // the attribution — the paraphrase in circulation (schema.claimQuoteText) differs from the
  // documented sentence carried by Quotation.text. There the "hero must not be the magnet" test
  // below is a false positive: creator names whoever wrote `text`, which is exactly right, and the
  // ClaimReview separately rates the paraphrase claim. Keyed on claimQuoteText, so records that
  // don't distinguish the two strings are unaffected.
  const wordingDrift = !!(s.claimQuoteText && plain(s.claimQuoteText) !== plain(quotation.text));
  // On a disputed page, emit Quotation.creator ONLY when it names the TRUE author: it must match the
  // hero, the hero must be a real named person, AND the hero must NOT be the magnet (unless this is
  // a wording-drift page, where magnet == true author by definition). This catches records where
  // generate left answer.authorName as the wrongly-credited name (else the machine-readable creator
  // would assert the very misattribution the page debunks).
  const creatorOk = s.creator && (q.confidence !== 'disputed'
    || (!heroUnknown && plain(s.creator.name).toLowerCase() === heroName.toLowerCase()
      && (wordingDrift || heroName.toLowerCase() !== magnetName)));
  if (creatorOk) {
    quotation.creator = { '@type': 'Person', name: s.creator.name };
    if (s.creator.birthDate) quotation.creator.birthDate = s.creator.birthDate;
    if (s.creator.deathDate) quotation.creator.deathDate = s.creator.deathDate;
    if (s.creator.jobTitle) quotation.creator.jobTitle = s.creator.jobTitle;
    // The RULE in CLAUDE.md asks for creator.description; jobTitle stays for records that only carry it.
    if (s.creator.description) quotation.creator.description = s.creator.description;
    if (s.creator.sameAs) quotation.creator.sameAs = s.creator.sameAs;
  }
  if (s.dateCreated) quotation.dateCreated = s.dateCreated;
  // isPartOf = the work this sentence is CONTAINED IN (e.g. the Meditations itself). Distinct from
  // isBasedOn below, which points at the specific translation the English wording comes from. A
  // translated quote legitimately needs both: the ancient work it belongs to, and the edition quoted.
  if (s.isPartOf) {
    const p = s.isPartOf;
    quotation.isPartOf = { '@type': p.type || 'CreativeWork', name: p.name };
    if (p.datePublished) quotation.isPartOf.datePublished = p.datePublished;
    if (p.sameAs) quotation.isPartOf.sameAs = p.sameAs;
  }
  if (s.isBasedOn) {
    const b = s.isBasedOn;
    quotation.isBasedOn = { '@type': b.type || 'CreativeWork', name: b.name };
    if (b.periodicalName) quotation.isBasedOn.isPartOf = { '@type': 'Periodical', name: b.periodicalName };
    if (b.datePublished) quotation.isBasedOn.datePublished = b.datePublished;
    if (b.pagination) quotation.isBasedOn.pagination = b.pagination;
    if (b.sameAs) quotation.isBasedOn.sameAs = b.sameAs;
    // sameAs asserts the linked URL IS this work. For a source we only know via a third-party
    // reference (a Wikiquote entry that merely CITES a pamphlet), that's a false identity claim —
    // use `citation` instead. `description` lets a record say what the relationship actually is,
    // e.g. "earliest documented antecedent", so isBasedOn isn't read as "the text came from here".
    if (b.citation) quotation.isBasedOn.citation = b.citation;
    if (b.description) quotation.isBasedOn.disambiguatingDescription = b.description;
  }
  // Rights → structured, so agents get reuse status without scraping prose.
  const rights = q.source && q.source.rights;
  if (rights === 'public-domain') {
    quotation.license = 'https://creativecommons.org/publicdomain/mark/1.0/';
    quotation.isAccessibleForFree = true;
  } else if (rights === 'in-copyright') {
    // A record whose `text` and `alternateName` have DIFFERENT rights status (an in-copyright
    // original plus a later anonymous rewrite the page says is unowned) can't be described by the
    // blanket notice — it would assert ownership over the paraphrase. schema.copyrightNotice lets
    // such a record scope the claim to the string that actually carries the right.
    quotation.copyrightNotice = s.copyrightNotice
      || 'In copyright' + (q.source.rightsHolder ? ' — ' + plain(q.source.rightsHolder) : '');
  }
  if (rights) quotation.usageInfo = `${ORIGIN}/how-we-verify`;

  const webpage = {
    '@type': 'WebPage',
    '@id': url,
    name: s.webPageName || q.meta.ogTitle,
    dateModified: s.dateModified,
    publisher: { '@type': 'Organization', name: 'Quotle.info', url: ORIGIN },
    mainEntity: { '@id': `${url}#quotation` },
  };

  // ClaimReview — the canonical fact-check schema. Rates the claim "{who} said {quote}":
  // verified → the true author, true (5/5); attributed → plausible/unproven (3); disputed →
  // the popularly-credited (wrong) name, false (1). The Quotation.creator still names the REAL
  // author, so a machine reads both "the claim about {who} is {rating}" and "actually by {creator}".
  const RATING = { verified: [5, 'Verified'], attributed: [3, 'Attributed'], disputed: [1, 'Disputed'] };
  const [ratingValue, defaultRatingName] = RATING[q.confidence] || RATING.verified;
  // `confidence` describes the quote's ORIGIN; this ClaimReview rates the narrower "{who} said it"
  // claim, which can be flatly false even while the origin stays disputed. Records where the cited
  // fact-checks are decisive (e.g. Monticello "Spurious" + CheckYourFact "False") can override the
  // label via schema.claimRatingName so it matches ratingValue 1 rather than implying a live dispute.
  const ratingName = (q.schema && q.schema.claimRatingName) || defaultRatingName;
  const trueAuthor = plain((q.answer && q.answer.authorName) || (s.creator && s.creator.name) || '');
  const firstMisWho = q.misattribution && q.misattribution.items && q.misattribution.items[0] && plain(q.misattribution.items[0].who);
  // The claimant is the MAGNET — the name the false claim is actually made under — which the record
  // carries as `creditedTo`. It is NOT misattribution.items[0].who: that field holds whatever the
  // first fact-check row happens to be about, which is routinely the propagation VECTOR rather than
  // the magnet ("Reader's Digest, June 1954", "ESPN", "Anonymous (internet)"), a work ("Not in the
  // Tao Te Ching"), or plain prose ("Not Mahatma Gandhi"). Using it emitted claimReviewed strings
  // like `Reader's Digest, June 1954 said: "..."` rated Disputed 1/5 — rating a TRUE statement false,
  // typing a magazine as a Person, and asking voice assistants "Did ESPN say ...?". 59 of 431
  // disputed pages were affected. creditedTo first, with the old chain as fallback for records
  // that predate it.
  const magnet = plain(q.creditedTo);
  const claimant = (q.confidence === 'disputed') ? (magnet || firstMisWho || trueAuthor) : trueAuthor;
  const quoteText = plain(quotation.text);
  // The claim under review is "{who} said {X}". On a paraphrase page, X is the polished wording that
  // actually circulates over the magnet's name — NOT Quotation.text, which carries the documented
  // origin nobody ever credited to the magnet. Records where the two differ set schema.claimQuoteText
  // so ClaimReview/FAQ rate the claim that was really made rather than a strawman.
  const claimQuoteText = plain(s.claimQuoteText) || quoteText;
  // Some claims cannot be stated honestly in the "{who} said {X}" template. A genuine quote whose
  // FAMOUS ENGLISH is a translator's needs the caveat inside claimReviewed itself, or a consumer
  // that lifts only the ClaimReview emits "{ancient author} said {modern translator's words} —
  // Verified", reproducing the exact error the page exists to correct. schema.claimReviewed lets
  // such a record state the reviewed claim in full.
  const claimReviewedText = plain(s.claimReviewed)
    || (claimant ? `${claimant} said: "${claimQuoteText}"` : `"${claimQuoteText}"`);
  const claimReview = {
    '@type': 'ClaimReview',
    '@id': `${url}#claimreview`,
    url,
    author: { '@type': 'Organization', name: 'Quotle.info', url: ORIGIN },
    datePublished: s.dateModified,
    claimReviewed: claimReviewedText,
    itemReviewed: {
      '@type': 'Claim',
      author: claimant ? { '@type': 'Person', name: claimant } : undefined,
      appearance: { '@id': `${url}#quotation` },
    },
    reviewRating: {
      '@type': 'Rating',
      ratingValue, bestRating: 5, worstRating: 1,
      alternateName: ratingName,
    },
  };
  if (!claimReview.itemReviewed.author) delete claimReview.itemReviewed.author;

  // FAQPage — the literal "Did {who} say {quote}?" Q&A, so AI answer-engines and snippets can
  // lift the verdict verbatim. Question uses the credited name; answer leads with the verdict.
  const verdictLead = q.confidence === 'disputed' ? 'No. ' : q.confidence === 'attributed' ? 'Not confirmed. ' : 'Yes. ';
  const answerText = (verdictLead + plain((q.answer && q.answer.sourceLine) || (q.answer && q.answer.label) || '')).replace(/\s+/g, ' ').trim();
  const faq = {
    '@type': 'FAQPage',
    '@id': `${url}#faq`,
    mainEntity: [{
      '@type': 'Question',
      name: claimant ? `Did ${claimant} say "${claimQuoteText}"?` : `Who really said "${claimQuoteText}"?`,
      acceptedAnswer: { '@type': 'Answer', text: answerText, url },
    }],
  };

  // BreadcrumbList — the same trail the visible nav renders (crumbTrail is the single source), so
  // search results can show the path instead of a bare URL. The current page carries no `item`,
  // per Google's spec for the final crumb.
  const breadcrumb = {
    '@type': 'BreadcrumbList',
    '@id': `${url}#breadcrumb`,
    itemListElement: crumbTrail(q).map((c, i) => {
      const item = { '@type': 'ListItem', position: i + 1, name: plain(c.name) };
      if (c.href) item.item = c.href === '/' ? `${ORIGIN}/` : `${ORIGIN}${c.href}`;
      return item;
    }),
  };

  return { '@context': 'https://schema.org', '@graph': [quotation, claimReview, webpage, faq, breadcrumb] };
}

// ---- top nav + breadcrumb ------------------------------------------------
// The ONE breadcrumb trail, rendered twice: as the visible nav and as BreadcrumbList JSON-LD.
// Deriving them separately is how the ClaimReview claimant bug happened — two call sites computing
// the same fact independently, one of them wrong for months. Change the trail here or nowhere.
//
// The trail is an ATTRIBUTION path (Home › who it's filed under › the quote), not a history of how
// you arrived. A prerendered page has exactly one trail, and a quote belongs to several themes at
// once (this one is both Friendship and Resilience), so there is no single true theme trail to show.
// The route back to a theme is the theme link row in the body — see renderThemes.
function crumbTrail(q) {
  const a = q.author || {};
  // On a page whose verdict is that the line has no known author, filing it under the author-card
  // person re-attributes it — the same error class the page exists to correct. `breadcrumbSection`
  // lets such a record route the crumb through the quote taxonomy instead, keeping the author card
  // as an in-body reference.
  const sec = q.breadcrumbSection;
  const trail = [{ name: 'Home', href: '/' }];
  if (sec) trail.push({ name: sec.name, href: sec.href || null });
  else if (a.name) trail.push({ name: a.name, href: authorLinked(a.slug) ? `/authors/${a.slug}` : null });
  trail.push({ name: q.breadcrumbLeaf || q.displayQuote, href: null, current: true });
  return trail;
}

function renderNav(q) {
  const crumbs = crumbTrail(q).map((c) => (c.current
    ? `<span aria-current="page">${esc(c.name)}</span>`
    : (c.href ? `<a href="${attr(c.href)}">${esc(c.name)}</a>` : `<span>${esc(c.name)}</span>`)))
    .join('<span class="sep" aria-hidden="true">›</span>\n        ');
  return `
${siteNav('')}
    <nav class="breadcrumb" aria-label="Breadcrumb">
        ${crumbs}
    </nav>`;
}

// ---- themes the quote is filed under -------------------------------------
// Without this every tagged quote page was a dead end: /themes/{slug} linked OUT to 678 quotes and
// nothing linked back, so the taxonomy ran one way. That cost a reader the route back to the theme
// they were browsing, and cost the theme pages their internal link graph — they were reachable only
// from /themes/, on a site whose whole bottleneck is getting crawled and indexed.
function renderThemes(q) {
  const themes = (q.themes || []).map((slug) => THEME_BY_SLUG[slug]).filter(Boolean);
  if (!themes.length) return '';
  const chips = themes.map((t) => `                <a class="theme-chip" href="/themes/${t.slug}/">${esc(t.label)}</a>`).join('\n');
  return `
        <!-- ============ THEMES ============ -->
        <section aria-labelledby="themes-h">
            <div class="sec-head"><p class="kicker">Explore</p><h2 id="themes-h">Filed under</h2><p class="sec-sub">More provenance-checked quotes on the same theme, each with its reuse status.</p></div>
            <div class="theme-chips">
${chips}
            </div>
        </section>`;
}

// ---- Layer 1: the answer -------------------------------------------------
function renderAnswer(q) {
  const conf = CONFIDENCE[q.confidence] || CONFIDENCE.verified;
  const ans = q.answer || {};
  const label = ans.label || conf.label;
  const confText = ans.confidenceText || conf.text;
  const nameInner = (ans.authorHref && authorLinked(q.author && q.author.slug))
    ? `<a href="${attr(ans.authorHref)}">${esc(ans.authorName)}</a>`
    : esc(ans.authorName);
  const dates = ans.authorDates
    ? `\n                    <span class="author-dates">${esc(ans.authorDates)}</span>`
    : '';
  return `
        <!-- ============ LAYER 1: THE ANSWER ============ -->
        <article class="answer" aria-labelledby="quote-heading">
            <p class="kicker">${esc(ans.kicker || 'Who really said it')}</p>
            <h1 class="the-quote" id="quote-heading">${esc(q.displayQuote)}</h1>
            <div class="attribution-row">
                <div class="author-block">
                    <span class="lbl">${esc(label)}</span>
                    <span class="author-name">${nameInner}</span>${dates}
                </div>
                <span class="confidence ${conf.cls}">
                    <span class="dot" aria-hidden="true">${conf.glyph}</span>
                    <span><span class="visually-hidden">Attribution status: </span>${esc(confText)}</span>
                </span>
            </div>
            <p class="source-line">${ans.sourceLine}</p>
            <div class="actions">
                <button class="act-btn" id="copyBtn" type="button">Copy quote</button>
                <button class="act-btn" id="shareBtn" type="button">Share</button>
            </div>
            <p class="answer-foot">
                <span aria-hidden="true">🕓</span> Last verified ${esc(ans.lastVerified)} · <a href="/how-we-verify">how we verify</a>
            </p>
        </article>`;
}

// ---- The source ----------------------------------------------------------
function renderSource(q) {
  const src = q.source || {};
  const rows = (src.docMeta || [])
    .map((r) => `                    <dt>${esc(r.dt)}</dt><dd${r.ddClass ? ` class="${r.ddClass}"` : ''}>${r.dd}</dd>`)
    .join('\n');
  const cutTag = src.cutTag ? `\n                    <span class="cut-tag">${esc(src.cutTag)}</span>` : '';
  const excerptNote = src.excerptNote
    ? `\n                <p class="excerpt-note">${src.excerptNote}</p>` : '';
  const artifact = renderArtifact(src.artifact);
  const sourceLink = src.sourceLink
    ? `\n                <a class="source-link" href="${attr(src.sourceLink.url)}" target="_blank" rel="noopener">${esc(src.sourceLink.text)} <span aria-hidden="true">↗</span></a>` : '';
  const trail = (src.trail && src.trail.length)
    ? `\n                <div class="trail">
                    <p class="trail-title">${esc(src.trailTitle || 'How we verified this')}</p>
                    <ul>
${src.trail.map((li) => `                        <li>${li}</li>`).join('\n')}
                    </ul>
                </div>` : '';
  const rights = renderRights(src);
  const kicker = src.kicker || 'Provenance';
  const heading = src.heading || 'The source';
  return `
        <!-- ============ THE SOURCE ============ -->
        <section aria-labelledby="source-h">
            <div class="sec-head"><p class="kicker">${esc(kicker)}</p><h2 id="source-h">${esc(heading)}</h2></div>
            <div class="source-card">
                <dl class="doc-meta">
${rows}
                </dl>
                <p class="excerpt">
                    ${src.excerpt}${cutTag}
                </p>${excerptNote}${artifact}${sourceLink}${trail}${rights}
            </div>
        </section>`;
}

function renderArtifact(a) {
  if (!a) return '';
  return `
                <div class="artifact">
                    <span class="artifact-ic" aria-hidden="true">${esc(a.icon || '📄')}</span>
                    <div class="artifact-txt">
                        <div class="a-kind">${esc(a.kindLabel)}</div>
                        <a href="${attr(a.url)}" target="_blank" rel="noopener">${esc(a.linkText)}</a>
                    </div>
                </div>`;
}

function renderRights(src) {
  // Structured state wins; `publicDomain: true` is legacy shorthand for 'public-domain'.
  const state = src.rights || (src.publicDomain === true ? 'public-domain' : null);
  const r = state && RIGHTS[state];
  // No (recognized) state: fall back to legacy prose-only note for un-migrated records.
  if (!r) return src.rightsNote ? `\n                <p class="rights-note">${src.rightsNote}</p>` : '';
  const holder = src.rightsHolder ? ` of ${esc(src.rightsHolder)}` : '';
  const body = src.rightsNote || r.note.replace('{holder}', holder);
  // "Public domain" is a worldwide claim, but our evidence is routinely US-only (Gutenberg's own
  // status line says "Public domain in the USA"). Where a work is PD in the US yet still protected
  // elsewhere — e.g. a pre-1931 English translation whose translator died within the last 70 years —
  // `source.rightsLabel` lets the record scope the badge to the jurisdiction it can actually support.
  const label = src.rightsLabel || r.label;
  return `
                <div class="rights rights-${state}">
                    <span class="rights-badge"><span class="rights-mark" aria-hidden="true">${r.mark}</span>${esc(label)}</span>
                    <p class="rights-body">${body}</p>
                </div>`;
}

// ---- Put it on a slide (always) ------------------------------------------
// The presentation kit: the one thing an AI deck-builder gets wrong — a paste-ready
// CORRECT credit, an honest "can I reuse this?" line from the rights state, and image
// directions grounded in the quote's real context (not a generic stock vibe).
const cap = (s) => s ? s.charAt(0).toUpperCase() + s.slice(1) : s;

// The attribution tail, safe to prepend a single quoted line to. Some records store
// copyAttribution as a standalone share string that ALREADY leads with the quoted line
// (`"…quote…" — Author, source`); strip that leading quoted segment so callers can render
// `"quote" + creditLine` without duplicating the quote. Records that store just the tail
// (`Author (attributed) — …`) pass through unchanged.
function creditLine(q) {
  const raw = (q.copyAttribution != null) ? q.copyAttribution : `— ${plain((q.answer || {}).authorName || '')}`;
  return raw.replace(/^\s*["“][^"”]*["”][.,]?\s*[—–-]?\s*/, '').trim() || raw;
}

// The quote string the presentation kit and the copy/share buttons emit. Defaults to displayQuote
// (the H1/slug form), which is what every record wants. But a record whose displayQuote is the
// POPULAR CLIPPING of a longer verified sentence must not have the site's own paste-ready
// deliverable ship the very truncation the page exists to correct — pinning a clipped fragment to
// a page number asserts that page contains that string, which it doesn't. Such a record sets
// presentation.verifiedQuote to the full sourced text; the H1/slug stay clipped (that's the form
// people search for, and JSON-LD already carries it as alternateName).
function kitQuote(q) {
  return plain((q.presentation && q.presentation.verifiedQuote) || q.displayQuote);
}

function buildImagePrompts(q) {
  // Records may carry authored prompts (presentation.imagePrompts[]); use them if present.
  if (q.presentation && Array.isArray(q.presentation.imagePrompts) && q.presentation.imagePrompts.length) {
    return q.presentation.imagePrompts.slice(0, 2);
  }
  const quote = plain(q.displayQuote);
  const who = plain((q.author && q.author.name) || (q.answer && q.answer.authorName) || '').trim();
  // metaLine is "dates · role · role" — drop the leading date clause, keep the role/era cues.
  const meta = plain((q.author && q.author.metaLine) || '');
  const era = meta.includes('·') ? meta.slice(meta.indexOf('·') + 1).trim() : meta.trim();
  const ground = era ? `evoking the world of ${who} — ${era}` : (who ? `evoking the world of ${who}` : 'evoking the theme of the line');
  const inContext = `${cap(ground)}. Theme: "${quote}". Atmospheric and restrained, cinematic directional light, a muted period-appropriate palette, fine grain and texture. Compose with generous empty space for the quote and a small credit line. No lettering in the image itself.`;
  const minimalist = `Minimalist editorial slide for the quote "${quote}". Clean background, a single muted accent color, generous negative space, subtle paper or linen texture, no literal illustration — let the words carry it. Reserve clear space for a serif quote and a small credit line. No lettering in the image itself.`;
  return [inContext, minimalist];
}

function renderPresentationKit(q) {
  const credit = creditLine(q);
  const quote = kitQuote(q);

  const state = q.source && (q.source.rights || (q.source.publicDomain === true ? 'public-domain' : null));
  const u = state && USE[state];
  const holder = (q.source && q.source.rightsHolder) ? ` (rights held by ${esc(q.source.rightsHolder)})` : '';
  // A record may author its own reuse line (`source.useLine`, plus optional `useTone`/`useIcon`).
  // Needed where neither a rights state nor the no-provenance fallback tells the truth — e.g. a page
  // whose ATTRIBUTION is settled but whose REUSE status is not (first publication date unestablished).
  // Without this, the fallback below tells readers not to assert an author the page has just proven.
  const own = q.source && q.source.useLine;
  const useLine = own || (u ? u.line.replace('{holder}', holder)
    : 'We couldn&rsquo;t verify where this wording comes from, so there&rsquo;s no rights status to give. Safe to present as an unverified or anonymous line &mdash; just don&rsquo;t assert a specific author or source.');
  const useTone = (q.source && q.source.useTone) || (u ? u.tone : 'warn');
  const useIcon = (q.source && q.source.useIcon) || (u ? u.icon : '?');

  // Don't name a "correct credit" here — the pkit-credit blockquote directly above already shows it.
  // (Naming answer.authorName could self-contradict when a record left it as the magnet.)
  // On a WORDING-DRIFT page (schema.claimQuoteText differs from the documented schema.quotationText)
  // the magnet IS the true author and only the wording drifted, so "crediting this to X is the
  // mistake" contradicts the page's own verdict — and the credit shown above names that very person.
  // The block label and the reuse line already carry the real caution, so say nothing here instead of
  // something false. Keyed on claimQuoteText, so ordinary wrong-name records are unaffected.
  const sch = q.schema || {};
  // Is the DISPUTE about the wording, or about the credit? A record that carries a distinct
  // claimQuoteText is saying "the line in circulation differs from the documented sentence" —
  // that's a wording dispute. Everything else disputed is a wrong-name dispute, where the wording
  // is usually verbatim correct and only the attribution is false.
  const wordingDrift = !!(sch.claimQuoteText && plain(sch.claimQuoteText) !== plain(sch.quotationText || q.displayQuote));
  const drift = wordingDrift
    && plain(q.creditedTo).toLowerCase() === plain((q.answer || {}).authorName || '').toLowerCase();
  const warn = (q.confidence === 'disputed' && q.creditedTo && !drift) ? `
                    <p class="pkit-warn"><span aria-hidden="true">⚠</span> The slide-ready mistake: crediting this to <strong>${esc(q.creditedTo)}</strong>. Use the credit shown above instead.</p>` : '';

  const [imgA, imgB] = buildImagePrompts(q);

  // The block label is an attribution claim of its own. "Verified quote & credit" is only true on a
  // verified page: stamped on a disputed or unproven record it contradicts the confidence badge a
  // few hundred pixels above, and a skimmer who copies the block is told the opposite of the page's
  // finding. Track the verdict instead — and on a non-verified page drop the gold accent bar, whose
  // whole job is to signal an authentic voice.
  // Name the dispute the page actually found — the label is a claim of its own, so it has to be true
  // for THIS record, not for the common case. Three distinct kinds hide under `disputed`:
  //   credit  — the wording is verbatim right, the name is wrong. Mary Schmich really did write
  //             "Do one thing every day that scares you"; Eleanor Roosevelt just didn't.
  //   wording — the name is right, the line in circulation isn't what they wrote (Camus).
  //   neither — nothing is securely documented at all.
  // Only ~9 records carry claimQuoteText, so wordingDrift alone can't classify the rest; fall back
  // to the unqualified "Disputed", which is true of every disputed page, rather than guessing.
  const creditDisputed = !!q.creditedTo
    && plain(q.creditedTo).toLowerCase() !== plain((q.answer || {}).authorName || '').toLowerCase();
  const kitLbl = q.confidence === 'disputed'
    ? (creditDisputed ? 'Disputed credit &mdash; copy with the correction'
      : wordingDrift ? 'Disputed wording &mdash; copy with the correction'
        : 'Disputed &mdash; copy with the correction')
    : q.confidence === 'attributed' ? 'Unconfirmed quote &amp; credit'
      : 'Verified quote &amp; credit';
  const cardCls = q.confidence === 'verified' || !q.confidence ? 'pkit-card' : `pkit-card pkit-card-${q.confidence}`;

  return `
        <!-- ============ PUT IT ON A SLIDE ============ -->
        <section class="pkit" aria-labelledby="pkit-h">
            <div class="sec-head"><p class="kicker">For presentations</p><h2 id="pkit-h">Put it on a slide</h2></div>
            <div class="${cardCls}">
                <div class="pkit-block">
                    <p class="pkit-lbl">${kitLbl}</p>
                    <blockquote class="pkit-credit" id="kitCredit">&ldquo;${esc(quote)}&rdquo; <span class="pkit-cite">${esc(credit)}</span></blockquote>
                    <button class="kit-copy act-btn" data-target="kitCredit" type="button">Copy quote + credit</button>${warn}
                </div>
                <div class="pkit-block pkit-use pkit-tone-${useTone}">
                    <p class="pkit-lbl">Can you use it?</p>
                    <p class="pkit-useline"><span class="pkit-ic" aria-hidden="true">${useIcon}</span> ${useLine}</p>
                </div>
                <div class="pkit-block">
                    <p class="pkit-lbl">Image direction <span class="pkit-sub">&mdash; grounded in this quote&rsquo;s real context; paste into your image tool</span></p>
                    <div class="pkit-imgs">
                        <div class="pkit-img">
                            <p class="pkit-img-t">In context</p>
                            <p class="pkit-prompt" id="kitImg1">${esc(imgA)}</p>
                            <button class="kit-copy act-btn small" data-target="kitImg1" type="button">Copy prompt</button>
                        </div>
                        <div class="pkit-img">
                            <p class="pkit-img-t">Minimalist</p>
                            <p class="pkit-prompt" id="kitImg2">${esc(imgB)}</p>
                            <button class="kit-copy act-btn small" data-target="kitImg2" type="button">Copy prompt</button>
                        </div>
                    </div>
                </div>
            </div>
        </section>`;
}

