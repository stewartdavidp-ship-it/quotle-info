        // Home > Themes > Friendship > quote — instead of the static attribution trail.
        // Uses document.referrer, not a ?from= param: same-origin navigations send the full path,
        // so this needs no query string. A param would mint a second crawlable URL per quote per
        // theme and fight the canonical, to buy nothing a crawler can use anyway.
        // Progressive enhancement only. Arrive direct, from search, or as a crawler and the static
        // attribution crumb (and the BreadcrumbList JSON-LD, which stays the canonical hierarchy)
        // is what you get. The theme is only shown if this quote genuinely carries it — the chip
