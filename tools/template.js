function buildJsonLd(q, url) {
  const s = q.schema || {};
  const quotation = {
    '@type': 'Quotation',
    '@id': `${url}#quotation`,
    text: s.quotationText || q.fullQuote || q.displayQuote,
  };
  if (s.alternateName) quotation.alternateName = s.alternateName;
  // The DISPLAYED quote text is always English on Quotle.info, so the Quotation's own language is 'en'.
  // (The old deferral worried about records that set s.inLanguage to the ORIGINAL composition language
  // of a translated source, e.g. "grc" — but that belongs on the SOURCE work via isPartOf.inLanguage
  // below, NOT on the English sentence in `text`. Language-of-`text` is unambiguously 'en'.)
  quotation.inLanguage = 'en';
  // Quotation.creator must name the TRUE author. On a DISPUTED page, generate sometimes left the
  // magnet (the wrongly-credited name) in schema.creator — a machine-readable contradiction of the
  // page's own verdict. So on disputed pages, only assert a creator when it genuinely matches the
  // true author (answer.authorName) and that author is a real named person; otherwise omit it. The
  // disputed claimant is still carried by the ClaimReview below, so nothing is lost.
  const heroName = plain((q.answer && q.answer.authorName) || '');
  const heroUnknown = !heroName || /\b(unknown|anonymous|unattributed|uncertain)\b/i.test(heroName);
  const magnetName = plain(primaryCredit(q) || '').toLowerCase();
  // A page with TWO quote strings: the paraphrase in circulation (schema.claimQuoteText) differs
  // from the documented sentence carried by Quotation.text. Used below to pick the ClaimReview
  // claimant — a page like that may have no magnet at all (a film misquote credits the right film),
  // so `misattribution.items[0].who` must not be pressed into service as one.
  //
  // This is NOT the test for "right person, wrong words" — see rightPersonWrongWords below. Two
  // different strings is a property of the WORDING; whether the credited person is nonetheless the
  // true author is a property of the ATTRIBUTION, and the corpus carries both shapes independently.
  const wordingDrift = !!(s.claimQuoteText && plain(s.claimQuoteText) !== plain(quotation.text));
  // RIGHT PERSON, WRONG WORDS — the credited name IS the true author and the dispute is the WORDING,
  // not the attribution (Franklin really wrote it, but about wine; Durocher really said it, but
  // differently). There the "hero must not be the magnet" test below is a false positive: creator
  // names whoever wrote `text`, which is exactly right, and the ClaimReview separately rates the
  // paraphrase claim.
  //
  // The exemption used to be keyed on `wordingDrift`, i.e. on claimQuoteText being present and
  // different. That proxy was wrong in BOTH directions:
  //   - too narrow — a record can state the same shape in prose without splitting the two strings.
  //     12 genuine right-person-wrong-words pages carried no claimQuoteText, so creator was suppressed
  //     and disambiguatingDescription fell through to "…The true author is not established", flatly
  //     contradicting the page's own prose and dropping the Schema.org creator the CLAUDE.md RULE asks
  //     for, undeclared.
  //   - too broad — claimQuoteText also differs on pages where the credited name really IS wrong
  //     (houston-we-have-a-problem: credited Jim Lovell, the words are Jack Swigert's). There the
  //     exemption let the magnet through as Quotation.creator, asserting the misattribution the page
  //     exists to debunk.
  //
  // The correct condition is about the ATTRIBUTION, and every field it needs already exists. The
  // record states who really said it in `answer.realAuthorName` — the explicit override, absent
  // precisely when `answer.authorName` is already the real author (see realAuthorName() at the foot
  // of this file). So the credited person is the true author exactly when the hero is the magnet AND
  // the record does not name somebody else as real. "Unknown"/"Anonymous" in realAuthorName counts as
  // somebody else: it says the true author is NOT established, which is a misattribution page, not a
  // wording one. No new field; no DOSSIER_SCHEMA change.
  const explicitReal = plain((q.answer && q.answer.realAuthorName) || '');
  const rightPersonWrongWords = !!(q.confidence === 'disputed' && !heroUnknown && magnetName
    && heroName.toLowerCase() === magnetName
    && (!explicitReal || explicitReal.toLowerCase() === magnetName));
  // On a disputed page, emit Quotation.creator ONLY when it names the TRUE author: it must match the
  // hero, the hero must be a real named person, AND the hero must NOT be the magnet (unless this is
  // a right-person-wrong-words page, where magnet == true author by definition). This catches records
  // where generate left answer.authorName as the wrongly-credited name (else the machine-readable
  // creator would assert the very misattribution the page debunks).
  //   EXCEPTION: when the true author is itself Unknown/Anonymous AND the record's creator names that
  //   same anonymous origin (never the magnet), emit it. Otherwise anonymous disputed pages shipped
  //   NO Quotation.creator at all — a CLAUDE.md RULE violation the audit flagged on ~30 pages — and an
  //   honest creator:"Unknown" asserts nothing false. (Guarded so a record can't sneak the magnet in
  //   under an "unknown" hero: the creator name must itself be the anonymous token.)
  const creatorIsAnon = s.creator && /\b(unknown|anonymous|unattributed|uncertain)\b/i.test(plain(s.creator.name));
  const creatorOk = s.creator && (q.confidence !== 'disputed'
    || (!heroUnknown && plain(s.creator.name).toLowerCase() === heroName.toLowerCase()
      && (rightPersonWrongWords || heroName.toLowerCase() !== magnetName))
    || (heroUnknown && creatorIsAnon));
  if (creatorOk) {
    quotation.creator = { '@type': 'Person', name: s.creator.name };
    // An anonymous creator must SAY it is anonymous. Emitting a bare Person named "Anonymous" keeps
    // the CLAUDE.md RULE satisfied but reads to a consumer exactly like a byline — indistinguishable
    // from crediting a person of that name. The name alone cannot carry the distinction, so the node
    // states it. (The alternative — dropping the creatorIsAnon arm — would silently revert the fix
    // that put a creator back on ~30 anonymous disputed pages, so it is not the right lever.)
    if (creatorIsAnon) {
      quotation.creator.disambiguatingDescription =
        'Not a named individual. The true author is unknown; this records that the origin is anonymous rather than crediting anyone.';
    }
    if (s.creator.birthDate) quotation.creator.birthDate = s.creator.birthDate;
    if (s.creator.deathDate) quotation.creator.deathDate = s.creator.deathDate;
    if (s.creator.jobTitle) quotation.creator.jobTitle = s.creator.jobTitle;
    // The RULE in CLAUDE.md asks for creator.description; jobTitle stays for records that only carry it.
    if (s.creator.description) quotation.creator.description = s.creator.description;
    if (s.creator.sameAs) quotation.creator.sameAs = s.creator.sameAs;
    // A pen name belongs to the PERSON, not to the quotation. Two fix agents hit this independently
    // on the Voltaire records: the remedy was "delete the Quotation-level alternateName and put it
    // on the creator", and the delete half worked while the add half was silently dropped here —
    // so the false assertion (that the QUOTE is also called "Francois-Marie Arouet") went away and
    // the birth name went with it. Exactly the shape the README warns about: a record edit that
    // looks fixed and ships unchanged markup.
    if (s.creator.alternateName) quotation.creator.alternateName = s.creator.alternateName;
  }
  if (s.dateCreated) quotation.dateCreated = s.dateCreated;
  // isPartOf = the work this sentence is CONTAINED IN (e.g. the Meditations itself). Distinct from
  // isBasedOn below, which points at the specific translation the English wording comes from. A
  // translated quote legitimately needs both: the ancient work it belongs to, and the edition quoted.
  if (s.isPartOf) {
    const p = s.isPartOf;
    quotation.isPartOf = { '@type': p.type || 'CreativeWork', name: p.name };
    if (p.datePublished) quotation.isPartOf.datePublished = p.datePublished;
    if (p.sameAs) quotation.isPartOf.sameAs = p.sameAs;
    // Original composition language of the source work (e.g. "grc", "fr") when the English quote is a
    // translation — lives on the WORK, not on the English `text`. Prefer isPartOf's own, else the record's.
    const orig = p.inLanguage || s.inLanguage;
    if (orig && orig !== 'en') quotation.isPartOf.inLanguage = orig;
  }
  if (s.isBasedOn) {
    const b = s.isBasedOn;
    quotation.isBasedOn = { '@type': b.type || 'CreativeWork', name: b.name };
    if (b.periodicalName) quotation.isBasedOn.isPartOf = { '@type': 'Periodical', name: b.periodicalName };
    if (b.datePublished) quotation.isBasedOn.datePublished = b.datePublished;
    if (b.pagination) quotation.isBasedOn.pagination = b.pagination;
    if (b.sameAs) quotation.isBasedOn.sameAs = b.sameAs;
    // sameAs asserts the linked URL IS this work. For a source we only know via a third-party
    // reference (a Wikiquote entry that merely CITES a pamphlet), that's a false identity claim —
    // use `citation` instead. `description` lets a record say what the relationship actually is,
    // e.g. "earliest documented antecedent", so isBasedOn isn't read as "the text came from here".
    if (b.citation) quotation.isBasedOn.citation = b.citation;
    if (b.description) quotation.isBasedOn.disambiguatingDescription = b.description;
  }
  // A line spoken by a CHARACTER is not the author speaking. "Let us cultivate our garden" is
  // Candide's, and the visible page is careful about that while the structured data was not — there
  // was no passthrough at all, so a record adding the field would have been inert. Found by a fix
  // agent that correctly refused to write a field the generator drops on the floor.
  //
  // Placed as a SIBLING of the isPartOf/isBasedOn blocks, not inside one. The first attempt landed
  // it inside `if (s.isBasedOn)`, where it fired only for records carrying that field — and the
  // Candide record uses isPartOf, so it silently did nothing. Which is the very failure this
  // passthrough exists to fix, reproduced while fixing it.
  if (s.spokenByCharacter) quotation.spokenByCharacter = { '@type': 'Person', name: plain(s.spokenByCharacter) };
  // Rights → structured, so agents get reuse status without scraping prose.
  const rights = q.source && q.source.rights;
  if (rights === 'public-domain') {
    quotation.license = 'https://creativecommons.org/publicdomain/mark/1.0/';
    quotation.isAccessibleForFree = true;
  } else if (rights === 'in-copyright') {
    // A record whose `text` and `alternateName` have DIFFERENT rights status (an in-copyright
    // original plus a later anonymous rewrite the page says is unowned) can't be described by the
    // blanket notice — it would assert ownership over the paraphrase. schema.copyrightNotice lets
    // such a record scope the claim to the string that actually carries the right.
    quotation.copyrightNotice = s.copyrightNotice
      || 'In copyright' + (q.source.rightsHolder ? ' — ' + plain(q.source.rightsHolder) : '');
  }
  if (rights) quotation.usageInfo = `${ORIGIN}/how-we-verify/`;

  const webpage = {
    '@type': 'WebPage',
    '@id': url,
    name: s.webPageName || q.meta.ogTitle,
    dateModified: s.dateModified,
    publisher: { '@type': 'Organization', name: 'Quotle.info', url: ORIGIN },
    mainEntity: { '@id': `${url}#quotation` },
  };

  // ClaimReview — the canonical fact-check schema. Rates the claim "{who} said {quote}":
  // verified → the true author, true (5/5); attributed → plausible/unproven (3); disputed →
  // the popularly-credited (wrong) name, false (1). The Quotation.creator still names the REAL
  // author, so a machine reads both "the claim about {who} is {rating}" and "actually by {creator}".
  const RATING = { verified: [5, 'Verified'], attributed: [3, 'Attributed'], disputed: [1, 'Disputed'] };
  const [defaultRatingValue, defaultRatingName] = RATING[q.confidence] || RATING.verified;
  // The confidence→value map is right for the common case, but disputed's 1/5 is machine-readable
  // "entirely false" — correct for pure fabrications and plain misattributions, WRONG for the
  // minority the audit flagged: hedged fact-checks (PolitiFact "Mostly False" / Snopes "Mixture")
  // and used-but-not-coined lines (a real utterance the speaker didn't originate). Those set
  // schema.claimRatingValue (2 or 3) so the numeric rating matches the page's verdict instead of
  // overclaiming — the value twin of the schema.claimRatingName label override just below. Absent
  // (or non-numeric) → the confidence default, so every unflagged page is unchanged.
  const ratingValue = (q.schema && typeof q.schema.claimRatingValue === 'number')
    ? q.schema.claimRatingValue : defaultRatingValue;
  // `confidence` describes the quote's ORIGIN; this ClaimReview rates the narrower "{who} said it"
  // claim, which can be flatly false even while the origin stays disputed. Records where the cited
  // fact-checks are decisive (e.g. Monticello "Spurious" + CheckYourFact "False") can override the
  // label via schema.claimRatingName so it matches ratingValue 1 rather than implying a live dispute.
  const ratingName = (q.schema && q.schema.claimRatingName) || defaultRatingName;
  const trueAuthor = plain((q.answer && q.answer.authorName) || (s.creator && s.creator.name) || '');
  const firstMisWho = q.misattribution && q.misattribution.items && q.misattribution.items[0] && plain(q.misattribution.items[0].who);
  // The claimant is the MAGNET — the name the false claim is actually made under — which the record
  // carries as `creditedTo`. It is NOT misattribution.items[0].who: that field holds whatever the
  // first fact-check row happens to be about, which is routinely the propagation VECTOR rather than
  // the magnet ("Reader's Digest, June 1954", "ESPN", "Anonymous (internet)"), a work ("Not in the
  // Tao Te Ching"), or plain prose ("Not Mahatma Gandhi"). Using it emitted claimReviewed strings
  // like `Reader's Digest, June 1954 said: "..."` rated Disputed 1/5 — rating a TRUE statement false,
  // typing a magazine as a Person, and asking voice assistants "Is ... really by ESPN?". 59 of 431
  // disputed pages were affected. creditedTo first, with the old chain as fallback for records
  // that predate it.
  const magnet = plain(primaryCredit(q));
  // A WORDING-DRIFT page (track C film) has NO claimant by design: nobody is falsely credited, the
  // source is right and only the words drifted. Its fact-check row is about the wording, so the
  // record carries {who: "Luke, I am your father", scope: "The wording"} — `who` holds the QUOTE.
  // Falling back to it emitted `"Luke, I am your father" said: "No. I am your father."`, typed a
  // quote string as a Person, and asked assistants `Is ... really by "Luke, I am your father"?`.
  const quoteText = plain(quotation.text);
  // The claim under review is "{who} said {X}". X is the wording that actually CIRCULATES — the H1 /
  // slug / displayQuote, which is definitionally what people claim was said. It is NOT quotation.text
  // (schema.quotationText), which carries the DOCUMENTED origin nobody ever credited to the magnet:
  // on 218 pages the two differ, and defaulting to quotation.text rated a strawman — the Churchill
  // page reviewed "Churchill said 'Men and nations do behave wisely…'", the Eban original, a claim
  // nobody ever made. displayQuote is the claim; quoteText is the last-ditch fallback if it's empty.
  const claimQuoteText = plain(s.claimQuoteText) || plain(q.displayQuote) || quoteText;
  // Both quote strings are compared against, since a drift page's `who` may echo either the popular
  // wording or the documented one.
  // Strip surrounding quote marks (straight + curly) before comparing: a fact-check row often quotes
  // the wording — items[0].who = ‘"I'll never go hungry again"’ — and the leading quote char made the
  // 24-char prefix never match displayQuote, leaking the fragment in as a Person claimant.
  const dequote = (s) => String(s || '').replace(/^[\s"'‘’“”]+|[\s"'‘’“”]+$/g, '').toLowerCase().trim();
  const isQuoteNotPerson = (w) => {
    const x = dequote(w);
    if (!x) return false;
    return [claimQuoteText, quoteText, plain(q.displayQuote)].some((s2) => {
      const y = dequote(s2);
      return !!y && (x.includes(y.slice(0, 24)) || y.includes(x.slice(0, 24)));
    });
  };
  // A fallback claimant (no creditedTo) must be the MAGNET — a person. misattribution.items[0].who
  // is not reliably that: it is also populated with propagation VECTORS ("Internet quote-aggregator
  // sites"), anonymity notes ("Anonymous / unknown"), paraphrase tags ("A modern paraphrase"), and
  // sentences. Each was being typed as a schema.org Person and rated "X said {quote}" 1/5 — the r19
  // vector bug surviving on ~16 records that carry no creditedTo. A trailing parenthetical is a
  // scope qualifier, not part of the name ("Malcolm X (as popularly quoted)" → "Malcolm X"): strip
  // it. When what remains still doesn't read as a person, degrade to the bare-quote form, which is
  // always honest ("Who is X really by?"). Conservative: over-rejecting only loses the "is it by X"
  // framing on a page or two; naming the wrong entity ships a falsehood.
  const stripQual = (w) => String(w || '').replace(/\s*\([^)]*\)\s*$/, '').trim();
  const looksLikePerson = (w) => {
    const x = stripQual(w);
    if (!x || x.length > 60) return false;
    // Article words match on a following SPACE, not \b: \b after "the " fails on punctuation (so
    // "The ‘some’ variant" slipped through), while \b after "a" wrongly fires on the initial in
    // "A. A. Milne" (a real person). The longer vector words keep \b since they can't be initials.
    if (/^(a|an|the|no|not)\s/i.test(x)) return false;
    if (/^(modern|popular|internet|anonymous|unknown|various|multiple)\b/i.test(x)) return false;
    if (/\b(quote ?sites?|aggregator|inspirational|paraphrase[rd]?|quote culture|web-era|quote-book|goodreads|brainyquote|azquotes|passiton|no documented|no identifiable|the discourses|the handbook)\b/i.test(x)) return false;
    return /[A-ZÀ-Þ]/.test(x); // a real name carries a capital
  };
  const misWho = (firstMisWho && !isQuoteNotPerson(firstMisWho) && looksLikePerson(firstMisWho)) ? stripQual(firstMisWho) : '';
  // And do NOT end the disputed chain at trueAuthor. On a wording drift the true author is the
  // person who really DID write the real line — claiming "{writer} said {quote}" and rating it
  // Disputed 1/5 rates a TRUE statement false. That is the Reader's-Digest-as-claimant bug wearing
  // a different hat. With no claimant the template already degrades honestly: claimReviewed becomes
  // the bare quote and the FAQ asks "Who is X really by?" — which is the actual question.
  // A WORDING-DRIFT page (a film misquote: claimQuoteText differs from the documented quotation.text)
  // has NO magnet — nobody is falsely credited, the source is right and only the words drifted. So on
  // a drift page with no explicit creditedTo, do NOT fall back to misWho: items[0].who there is the
  // film ("Casablanca"), a character/actor ("Clint Eastwood"), or a fragment — none a magnet, all
  // typed as a schema.org Person and rated "X said {quote}" 1/5. Degrade to the bare quote instead.
  // Ordinary wrong-name records (no claimQuoteText) are unaffected and keep the misWho fallback.
  const claimant = (q.confidence === 'disputed') ? (magnet || (wordingDrift ? '' : misWho) || '') : trueAuthor;
  // Some claims cannot be stated honestly in the "{who} said {X}" template. A genuine quote whose
  // FAMOUS ENGLISH is a translator's needs the caveat inside claimReviewed itself, or a consumer
  // that lifts only the ClaimReview emits "{ancient author} said {modern translator's words} —
  // Verified", reproducing the exact error the page exists to correct. schema.claimReviewed lets
  // such a record state the reviewed claim in full.
  // THE VERB IS PART OF THE CLAIM. Default "said" is right for the ordinary case — the page exists
  // because someone did NOT say a thing. But a POPULARIZER page checks a different claim: the
  // credited person really did say the line, they just did not COIN it. Rating "Gary Player said:
  // '...'" 1/5 there asserts, machine-readably, that he never said it — while the visible label on
  // the same page reads "Not coined by Gary Player — an older saying he made famous". Prose hedged,
  // structured data flat and wrong, and only the structured data is what an answer engine reads.
  // Same failure as the Reader's-Digest-as-claimant bug, one field over.
  //
  // schema.claimVerb lets the record state which claim is being rated. 'coined' keeps the fact-check
  // (the coinage claim IS false, so the 1/5 stands) while no longer denying an utterance that
  // happened. schema.claimReviewed still overrides the whole sentence when a record needs to say
  // something this template cannot compose.
  const claimVerb = plain(s.claimVerb) || 'said';
  const claimReviewedText = plain(s.claimReviewed)
    || (claimant ? `${claimant} ${claimVerb}: "${claimQuoteText}"` : `"${claimQuoteText}"`);
  // itemReviewed.appearance defaults to #quotation — fine when #quotation carries the DISPUTED
  // string. But on right-person-wrong-words and paraphrase pages #quotation carries the GENUINE,
  // documented passage, so linking the reviewed (false) claim's appearance there asserts the claim
  // "appeared" in the author's authentic text — the opposite of the page's finding, and it drags the
  // Disputed rating onto the real quote for any consumer that follows the edge. Record-driven:
  // schema.claimAppearanceUrl points appearance at a real viral instance of the claim; else
  // schema.suppressClaimAppearance drops it entirely (the audit's primary remedy, since #quotation is
  // still reachable via the Quotation/WebPage nodes). Neither set → the #quotation default, unchanged.
  let appearance;
  if (s.claimAppearanceUrl) appearance = { '@id': s.claimAppearanceUrl };
  else if (!s.suppressClaimAppearance) appearance = { '@id': `${url}#quotation` };
  const claimReview = {
    '@type': 'ClaimReview',
    '@id': `${url}#claimreview`,
    url,
    author: { '@type': 'Organization', name: 'Quotle.info', url: ORIGIN },
    datePublished: s.dateModified,
    claimReviewed: claimReviewedText,
    itemReviewed: {
      '@type': 'Claim',
      author: claimant ? { '@type': 'Person', name: claimant } : undefined,
      appearance,
    },
    reviewRating: {
      '@type': 'Rating',
      ratingValue, bestRating: 5, worstRating: 1,
      alternateName: ratingName,
    },
  };
  if (!claimReview.itemReviewed.author) delete claimReview.itemReviewed.author;
  if (!claimReview.itemReviewed.appearance) delete claimReview.itemReviewed.appearance;

  // ADDITIONAL false credits get their OWN ClaimReview. A quote collects more than one wrong name —
  // the pessimist/optimist line is pinned on Churchill AND Rockefeller — and the visible prose has
  // always said so (misattribution.items[] is multi-entry on 1,005 pages). Only the structured data
  // stopped at the first name, so an answer engine could read "Churchill didn't say this" off the
  // page and still confidently repeat the Rockefeller version. One node per claimant fixes that;
  // schema.org allows many ClaimReviews in a graph, each rating a distinct claim.
  //
  // Deliberately NARROW. These fire only on a `disputed` record that has a real primary claimant,
  // so nothing changes for verified/attributed pages or for the wording-drift pages that carry no
  // magnet by design (see the long note above — naming a film or a propagation vector as a Person
  // and rating it 1/5 is the exact bug that took 59 pages to find). They reuse the primary's rating
  // and appearance: every name in the list is wrong in the same way and about the same claim.
  // schema.claimReviewed, when a record sets it, governs the PRIMARY node only — it is a
  // hand-authored sentence about the primary claimant and cannot be re-pointed at another name.
  const extraClaimReviews = (q.confidence === 'disputed' && claimant)
    ? otherCredits(q).map((name, i) => {
      const node = {
        '@type': 'ClaimReview',
        '@id': `${url}#claimreview-${i + 2}`,
        url,
        author: { '@type': 'Organization', name: 'Quotle.info', url: ORIGIN },
        datePublished: s.dateModified,
        claimReviewed: `${plain(name)} ${claimVerb}: "${claimQuoteText}"`,
        itemReviewed: {
          '@type': 'Claim',
          author: { '@type': 'Person', name: plain(name) },
          appearance,
        },
        reviewRating: {
          '@type': 'Rating',
          ratingValue, bestRating: 5, worstRating: 1,
          alternateName: ratingName,
        },
      };
      if (!node.itemReviewed.appearance) delete node.itemReviewed.appearance;
      return node;
    })
    : [];

  // FAQPage — the literal attribution Q&A, so AI answer-engines and snippets can lift the verdict
  // verbatim.
  //
  // The question is phrased "Is {quote} really by {who}?", NOT "Did {who} say {quote}?". `say` is a
  // SPOKEN verb, and most of this corpus is written: essays, letters, poems, novels, pamphlets. On
  // those pages "Did Emerson say '…'?" asks about an utterance nobody ever made, and an answer engine
  // lifting it repeats the category error. Nothing in the record distinguishes spoken from written
  // (no utterance-kind field exists, isPartOf.type is set on 28 of 1118 records, and source.docMeta
  // is free prose), so the question has to be verb-NEUTRAL rather than verb-correct. "by" covers
  // wrote / said / recorded / delivered alike, keeps the yes/no shape the verdict lead depends on and
  // the same polarity ("No." still means "not by them"), and still reads like a query a person types.
  // Same fix on the no-claimant branch, which asked "Who really said …?".
  //
  // The yes/no lead ("No." / "Not confirmed." / "Yes.") only answers the yes/no QUESTION form. When
  // there is no claimant the question is "Who is X really by?", which a "No." does not answer — and
  // pairing them was actively self-contradictory ("Who is X really by?" → "No. Wiesel really did say
  // this"). So only prepend the lead on the "Is … really by {claimant}?" form; the who-form answer
  // opens with the verdict sentence itself. (42 pages carried the mismatch.)
  const verdictLead = !claimant ? '' : q.confidence === 'disputed' ? 'No. ' : q.confidence === 'attributed' ? 'Not confirmed. ' : 'Yes. ';
  const answerText = (verdictLead + plain((q.answer && q.answer.sourceLine) || (q.answer && q.answer.label) || '')).replace(/\s+/g, ' ').trim();
  const faq = {
    '@type': 'FAQPage',
    '@id': `${url}#faq`,
    mainEntity: [{
      '@type': 'Question',
      name: claimant ? `Is "${claimQuoteText}" really by ${claimant}?` : `Who is "${claimQuoteText}" really by?`,
      acceptedAnswer: { '@type': 'Answer', text: answerText, url },
    }],
  };

  // BreadcrumbList — the same trail the visible nav renders (crumbTrail is the single source), so
  // search results can show the path instead of a bare URL. The current page carries no `item`,
  // per Google's spec for the final crumb.
  const breadcrumb = {
    '@type': 'BreadcrumbList',
    '@id': `${url}#breadcrumb`,
    itemListElement: crumbTrail(q).map((c, i) => {
      const item = { '@type': 'ListItem', position: i + 1, name: plain(c.name) };
      if (c.href) item.item = c.href === '/' ? `${ORIGIN}/` : `${ORIGIN}${c.href}`;
      return item;
    }),
  };

  // Quotation.disambiguatingDescription — THE PAGE'S VERDICT, in the machine-readable layer.
  //
  // Without this, a consumer that reads only the Quotation node gets an unqualified assertion:
  //   - on an `attributed` page, `creator` is emitted flatly even though no primary source was found;
  //   - on a `disputed` page where the true author IS known, `creator` is emitted with no signal that
  //     the popular attribution is contested;
  //   - on a `disputed` page where it is NOT known, `creator` is suppressed entirely (creatorOk) and
  //     the node simply goes quiet — a machine cannot tell "no author" from "author disputed".
  // The ClaimReview does carry the dispute, but it is a SEPARATE node and nothing obliges a consumer
  // to read it. That gap was r25's largest issue class: 20 of 66 issues were structured data
  // disagreeing with the prose on the same page — a site whose whole thesis is "this attribution is
  // wrong" telling Google the attribution is fine.
  //
  // Schema.org defines disambiguatingDescription as a short description used to disambiguate the item
  // from similar ones, which is exactly the job: it disambiguates THIS quotation from the naive
  // reading of its own creator field. It is emitted for all three confidence states so a consumer can
  // always read the verdict rather than inferring it from a field's absence.
  const verdictNote = (() => {
    // RECORD OVERRIDE, same shape as schema.claimRatingValue/claimRatingName/claimReviewed.
    // The computed strings below are derived only from confidence + creditedTo + creator, so a page
    // whose evidence is genuinely UNSETTLED had no way to say so in the machine-readable layer — it
    // got a flat verdict regardless. `it-is-too-probable-…` is the case that forced this: the page's
    // own truthLine reads "The sentiment may well be Washington's" and Wikiquote files the passage
    // under Disputed (not Misattributed) with Bancroft accepting it as genuine, while this field
    // asserted "Commonly misattributed to George Washington. Actually by Gouverneur Morris." Prose
    // hedged, structured data did not — and structured data is the half assistants read.
    // Unflagged pages are byte-identical; only a record that sets schema.verdictNote diverges.
    if (s.verdictNote) return plain(s.verdictNote);
    if (q.confidence === 'disputed') {
      const wrong = plain(magnet || misWho || '');
      // An anonymous creator is NOT a name to credit. `creatorIsAnon` pages legitimately emit
      // creator:"Anonymous" (see creatorOk above — it keeps ~30 pages RULE-compliant), but feeding
      // that token in here produced "Actually by Anonymous." — which reads as a byline for a person
      // who does not exist. Falling through instead reaches the realAuthorName / "not established"
      // branches below, which were written for exactly this state.
      const rawWho = quotation.creator && quotation.creator.name ? plain(quotation.creator.name) : '';
      const who = /\b(unknown|anonymous|unattributed|uncertain)\b/i.test(rawWho) ? '' : rawWho;
      // RIGHT PERSON, WRONG WORDS. When the magnet IS the true author the dispute is about the
      // WORDING, not the attribution — "Commonly misattributed to X. Actually by X." is gibberish,
      // and it is the very self-contradiction this field exists to prevent. validate-records already
      // warns on this shape ("real == credited"); ~a fifth of disputed records are it.
      if (who && wrong && who.toLowerCase() === wrong.toLowerCase()) {
        return `${who} is the author, but this popular wording is not what they wrote — it is a later paraphrase or misquotation.`;
      }
      const lead = wrong ? `Commonly misattributed to ${wrong}.` : 'This attribution is disputed.';
      if (who) return `${lead} Actually by ${who}.`;
      // `creator` is deliberately SUPPRESSED on pages where asserting it would name the magnet
      // (creatorOk), so its absence does NOT mean the record is ignorant. answer.realAuthorName is
      // the record's own explicit "who really said it" — consult it before claiming ignorance, or
      // the page tells a machine "the true author is not established" while the prose names them.
      // Houston is the clearest case: creator is correctly withheld (it would say Lovell), but the
      // record says Jack Swigert. Six pages read that way after PR #119; this is that fix.
      const named = plain((q.answer && q.answer.realAuthorName) || '');
      if (named && !/\b(unknown|anonymous|unattributed|uncertain)\b/i.test(named)) {
        return `${lead} Actually by ${named} — not asserted as creator here because the popular credit is contested.`;
      }
      // Two different states, and saying the wrong one contradicts the very same JSON-LD node.
      // When the anonymous arm of creatorOk fired, a creator IS present (name "Anonymous") — telling
      // a consumer "no creator is asserted here" in the field right beside it is self-refuting.
      if (rawWho) return `${lead} The true author is not established; the origin is recorded as anonymous.`;
      return `${lead} The true author is not established; no creator is asserted here.`;
    }
    if (q.confidence === 'attributed') {
      const who = trueAuthor || (quotation.creator && plain(quotation.creator.name)) || '';
      return who
        ? `Widely attributed to ${who}, but not traced to a primary source. Treat the attribution as unconfirmed.`
        : 'Widely repeated, but not traced to a primary source. Treat the attribution as unconfirmed.';
    }
    return 'Attribution traced to a primary source.';
  })();
  if (verdictNote) quotation.disambiguatingDescription = verdictNote;

  return { '@context': 'https://schema.org', '@graph': [quotation, claimReview, ...extraClaimReviews, webpage, faq, breadcrumb] };
}

// ---- top nav + breadcrumb ------------------------------------------------
// The ONE breadcrumb trail, rendered twice: as the visible nav and as BreadcrumbList JSON-LD.
// Deriving them separately is how the ClaimReview claimant bug happened — two call sites computing
// the same fact independently, one of them wrong for months. Change the trail here or nowhere.
//
// The trail is an ATTRIBUTION path (Home › who it's filed under › the quote), not a history of how
// you arrived. A prerendered page has exactly one trail, and a quote belongs to several themes at
// once (this one is both Friendship and Resilience), so there is no single true theme trail to show.
// The route back to a theme is the theme link row in the body — see renderThemes.
function crumbTrail(q) {
  const a = q.author || {};
  // On a page whose verdict is that the line has no known author, filing it under the author-card
  // person re-attributes it — the same error class the page exists to correct. `breadcrumbSection`
  // lets such a record route the crumb through the quote taxonomy instead, keeping the author card
  // as an in-body reference.
  const sec = q.breadcrumbSection;
  const trail = [{ name: 'Home', href: '/' }];
  // sec.href is record data (like ans.authorHref) — normalise it to the trailing-slash contract
  // rather than trusting it, or a record written before the fix puts a 301 in the breadcrumb AND
  // in the BreadcrumbList JSON-LD, which both derive from this trail.
  if (sec) trail.push({ name: sec.name, href: contractHref(sec.href) || null });
  else if (a.name) trail.push({ name: a.name, href: authorLinked(a.slug) ? `/authors/${a.slug}/` : null });
  trail.push({ name: q.breadcrumbLeaf || q.displayQuote, href: null, current: true });
  return trail;
}

function renderNav(q) {
  const crumbs = crumbTrail(q).map((c) => (c.current
    ? `<span aria-current="page">${esc(c.name)}</span>`
    : (c.href ? `<a href="${attr(c.href)}">${esc(c.name)}</a>` : `<span>${esc(c.name)}</span>`)))
    .join('<span class="sep" aria-hidden="true">›</span>\n        ');
  return `
${siteNav('')}
    <nav class="breadcrumb" aria-label="Breadcrumb">
        ${crumbs}
    </nav>`;
}

